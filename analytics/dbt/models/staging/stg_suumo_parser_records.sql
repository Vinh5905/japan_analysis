-- One source-conformed row per parser task. Operational raw wins when a task
-- also exists in the local notebook seed.
with operational_source as (
    select
        task_id, batch_id, source_id, data_hash, record ->> 'parsed_at' as parsed_at,
        {{ suumo_clean("record ->> 'SUUMO物件コード'") }} as suumo_property_code,
        (record ->> 'is_valid')::boolean as is_valid,
        record ->> '取り扱い店舗物件コード' as shop_property_code,
        record ->> '情報更新日' as information_updated_at_text,
        record ->> '入居' as move_in,
        record ->> '取引態様' as transaction_type,
        record ->> '契約期間' as contract_period,
        record ->> '所在地' as address,
        record ->> '駅徒歩' as station_access,
        record ->> '家賃' as rent_price_text,
        record ->> '管理費_共益費' as management_fee_text,
        record ->> 'ほか諸費用' as other_monthly_costs,
        record ->> '敷金' as deposit_text,
        record ->> '礼金' as key_money_text,
        record ->> '保証金' as guarantee_deposit_text,
        record ->> '敷引_償却' as depreciation_text,
        record ->> '仲介手数料' as brokerage_fee,
        record ->> 'ほか初期費用' as other_initial_costs,
        record ->> '保証会社' as guarantee_company,
        record ->> '間取り' as layout,
        record ->> '間取り詳細' as layout_detail,
        record ->> '専有面積' as exclusive_area_text,
        record ->> '築年数' as building_age_text,
        record ->> '築年月' as built_at_text,
        record ->> '階' as floor_text,
        record ->> '階建' as building_floors,
        record ->> '総戸数' as total_units,
        record ->> '建物種別' as building_type,
        record ->> '構造' as structure,
        record ->> '向き' as direction,
        record ->> '条件' as conditions,
        record ->> '損保' as insurance,
        record ->> '駐車場' as parking,
        record ->> 'エネルギー消費性能' as energy_efficiency,
        record ->> '断熱性能' as insulation_performance,
        record ->> '目安光熱費' as estimated_utility_cost,
        record ->> '備考' as remarks,
        'operational'::text as record_origin
    from {{ source('warehouse_raw', 'suumo_parser_records') }}
), seed_source as (
    select
        task_id::bigint as task_id,
        batch_id::bigint as batch_id,
        source_id::bigint as source_id,
        data_hash::text as data_hash,
        parsed_at::text as parsed_at,
        {{ suumo_clean('suumo_property_code') }} as suumo_property_code,
        is_valid::boolean as is_valid,
        shop_property_code::text as shop_property_code,
        information_updated_at_text::text as information_updated_at_text,
        move_in::text as move_in,
        transaction_type::text as transaction_type,
        contract_period::text as contract_period,
        address::text as address,
        station_access::text as station_access,
        rent_price_text::text as rent_price_text,
        management_fee_text::text as management_fee_text,
        other_monthly_costs::text as other_monthly_costs,
        deposit_text::text as deposit_text,
        key_money_text::text as key_money_text,
        guarantee_deposit_text::text as guarantee_deposit_text,
        depreciation_text::text as depreciation_text,
        brokerage_fee::text as brokerage_fee,
        other_initial_costs::text as other_initial_costs,
        guarantee_company::text as guarantee_company,
        layout::text as layout,
        layout_detail::text as layout_detail,
        exclusive_area_text::text as exclusive_area_text,
        building_age_text::text as building_age_text,
        built_at_text::text as built_at_text,
        floor_text::text as floor_text,
        building_floors::text as building_floors,
        total_units::text as total_units,
        building_type::text as building_type,
        structure::text as structure,
        direction::text as direction,
        conditions::text as conditions,
        insurance::text as insurance,
        parking::text as parking,
        energy_efficiency::text as energy_efficiency,
        insulation_performance::text as insulation_performance,
        estimated_utility_cost::text as estimated_utility_cost,
        remarks::text as remarks,
        'notebook_seed'::text as record_origin
    from {{ ref('suumo_parser_records_seed') }}
), combined as (
    select * from operational_source
    union all
    select * from seed_source
), source as (
    select distinct on (task_id) *
    from combined
    order by task_id,
             case record_origin when 'operational' then 1 else 2 end
)
select s.*,
       {{ suumo_clean('shop_property_code') }} as shop_property_code_clean,
       {{ suumo_clean('transaction_type') }} as transaction_type_clean,
       {{ suumo_norm('move_in') }} as n_move_in,
       {{ suumo_norm('contract_period') }} as n_contract,
       {{ suumo_clean('address') }} as n_address,
       {{ suumo_norm('layout') }} as n_layout,
       {{ suumo_norm('building_age_text') }} as n_age,
       {{ suumo_norm('built_at_text') }} as n_built,
       {{ suumo_norm('floor_text') }} as n_floor,
       {{ suumo_norm('building_floors') }} as n_building_floors,
       {{ suumo_norm('insurance') }} as n_insurance,
       {{ suumo_norm('parking') }} as n_parking,
       {{ suumo_clean('station_access') }} as n_station_access,
       {{ suumo_clean('layout_detail') }} as n_layout_detail
from source s
